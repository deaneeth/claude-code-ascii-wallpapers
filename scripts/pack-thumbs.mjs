// Packs the small thumbnails into hooks/thumbs.js as data URIs: the picker draws them without touching the disk.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = process.argv[2]
const root = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const out = {}

for (const f of readdirSync(dir).filter(f => f.endsWith('.mini.jpg')).sort()) {
  out[f.replace('.mini.jpg', '')] = 'data:image/jpeg;base64,' + readFileSync(join(dir, f)).toString('base64')
}

writeFileSync(join(root, 'hooks', 'thumbs.js'), '// generated by scripts/build-thumbs.sh: 288x162 JPEG thumbnails for the picker\nexport const THUMBS = ' + JSON.stringify(out) + '\n')
writeFileSync(join(root, 'hooks', 'thumbs.d.ts'), 'export const THUMBS: Record<string, string>\n')
console.log(Object.keys(out).length, 'thumbnails packed')
